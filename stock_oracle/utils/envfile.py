"""
Reading and saving stock_oracle/.env, shared by the Settings dialog and the
first-run wizard so both keep keys they don't manage.
"""
from pathlib import Path
from typing import Dict, Union

from stock_oracle.utils.atomic import write_text_atomic

# Keys the app no longer collects. Saving drops them from .env so stored
# brokerage logins don't linger (brokers.py is read-only).
RETIRED_ENV_KEYS = frozenset({"RH_EMAIL", "RH_PASSWORD", "RH_TOTP_SECRET",
                              "WEBULL_APP_KEY", "WEBULL_APP_SECRET"})


def read_env(path: Union[str, Path]) -> Dict[str, str]:
    """KEY=value pairs from an .env file; {} if it doesn't exist."""
    try:
        # utf-8-sig: a byte-order mark (PowerShell 5.1's "utf8", Notepad's
        # "UTF-8 with BOM") would otherwise become part of the first key
        text = Path(path).read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return {}
    values = {}
    for line in text.splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, _, val = line.partition("=")
            values[key.strip()] = val.strip().strip('"').strip("'")
    return values


def merge_env(existing_text: str, settings: Dict[str, str], stamp: str = "",
              source: str = "GUI") -> str:
    """
    New .env content: ``settings`` (the caller's fields; empty means cleared)
    plus every other key already in the file, e.g. TERMINAL_* or
    ALPACA_USE_SIP set by hand. Overwriting with only the caller's fields
    silently deleted those. Retired keys are dropped either way.
    """
    kept = []
    for line in existing_text.lstrip("﻿").splitlines():
        key, sep, _ = line.strip().partition("=")
        key = key.strip()
        if (sep and key and not key.startswith("#")
                and key not in settings and key not in RETIRED_ENV_KEYS):
            kept.append(line.strip())
    lines = [
        "# Stock Oracle Settings",
        f"# Generated by {source} - do not edit manually while app is running",
        f"# Last saved: {stamp}",
        "",
    ]
    lines += [f"{k}={v}" for k, v in sorted(settings.items())
              if v and k not in RETIRED_ENV_KEYS]
    if kept:
        lines += ["", "# Not managed by the Settings dialog (kept as-is)"] + kept
    return "\n".join(lines) + "\n"


def save_env(path: Union[str, Path], settings: Dict[str, str], stamp: str = "",
             source: str = "GUI"):
    """Merge ``settings`` into the file at ``path`` and write it atomically."""
    path = Path(path)
    try:
        existing = path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        existing = ""
    write_text_atomic(path, merge_env(existing, settings, stamp, source))
